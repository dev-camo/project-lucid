HEADER = "%YAML 1.1\n%TAG !u! tag:unity3d.com,2011:\n"


def binding(assembly, full_name, index):
    return dict(assembly=assembly, full_name=full_name, exported_guid=("%x" % index) * 32,
                target_guid=("%x" % (index + 6)) * 32, exported_file_id=11500000, target_file_id=11500000)


def standalone(row, name, own):
    return (HEADER + "--- !u!114 &11400000\nMonoBehaviour:\n"
            "  m_ObjectHideFlags: 0\n  m_CorrespondingSourceObject: {fileID: 0}\n"
            "  m_PrefabInstance: {fileID: 0}\n  m_PrefabAsset: {fileID: 0}\n"
            "  m_GameObject: {fileID: 0}\n  m_Enabled: 1\n  m_EditorHideFlags: 0\n"
            "  m_Script: {fileID: 11500000, guid: " + row["exported_guid"] + ", type: 3}\n"
            "  m_Name: " + name + "\n  m_EditorClassIdentifier:\n" + own).encode()


def pointer(index):
    return "{fileID: 11400000, guid: " + ("%x" % index) * 32 + ", type: 2}"


