class SceneComponentDocumentTests(unittest.TestCase):
    def test_nested_component_and_flat_peer_change_only_their_script_lines(self):
        content = scene()
        actual, count = rewrite_component_pointers(content, [VISUAL])
        self.assertEqual(1, count)
        self.assertEqual(swapped(content, VISUAL), actual)
        # The prepared dispatcher sends the flat GuiInitializer document to the scalar path.
        self.assertEqual((swapped(swapped(content, VISUAL), GUI), 2), rewrite_prepared_script_pointers(content, [VISUAL, GUI]))

    def test_payload_outside_profile_blocks_is_rejected(self):
        for visual in (VISUAL_BODY.replace("  m_sdAtlasSuffix: _SD\n", "  m_sdAtlasSuffix: _SD\n    stray: 1\n"),
                       VISUAL_BODY.replace("  m_devicePerformanceGroup: ", "  m_unknown: 1\n  m_devicePerformanceGroup: "),
                       VISUAL_BODY.replace("  m_sdAtlasSuffix: _SD\n", ""),
                       VISUAL_BODY.replace("    Level: -100\n", "    Level: -100\n  m_Script: {fileID: 1}\n"),
                       VISUAL_BODY.replace("  m_atlasesWithVariants:\n", "  m_atlasesWithVariants: []\n")):
            with self.subTest(visual=visual):
                with self.assertRaises(ValueError):
                    rewrite_component_pointers(scene(visual), [VISUAL])

    def test_scene_envelope_and_common_header_are_bounded(self):
        with self.assertRaises(ValueError):
            rewrite_component_pointers(scene().replace(b"m_GameObject: {fileID: 2}", b"m_GameObject: {fileID: 0}"), [VISUAL])
        with self.assertRaises(ValueError):
            rewrite_component_pointers(scene().replace(b"  m_Name:\n  m_EditorClassIdentifier:\n  m_requirementForHDUI",
                                                       b"  m_Name: x\n  m_EditorClassIdentifier:\n  m_requirementForHDUI"), [VISUAL])
        with self.assertRaises(ValueError):
            rewrite_component_pointers(scene().replace(b"--- !u!114 &11\n", b"--- !u!114 &11 stripped\n"), [VISUAL])
        with self.assertRaises(ValueError):
            rewrite_component_pointers(scene()[len(HEADER):], [VISUAL])
        # The selected GUID anywhere but its own script line.
        with self.assertRaises(ValueError):
            rewrite_component_pointers(scene(extra="--- !u!114 &12\nMonoBehaviour:\n  m_note: " + VISUAL["exported_guid"] + "\n"), [VISUAL])

    def test_unknown_owner_and_duplicate_bindings_are_rejected(self):
        with self.assertRaises(ValueError):
            rewrite_component_pointers(scene(), [GUI])
        with self.assertRaises(ValueError):
            rewrite_component_pointers(scene(), [VISUAL, dict(VISUAL)])


