def configuration(row, replace=None):
    name, body = BODIES[int(row["exported_guid"][0], 16)]
    if replace:
        assert replace[0] in body
        body = body.replace(*replace)
    return standalone(row, name, body)


def swapped(content, row):
    old = ("m_Script: {fileID: 11500000, guid: " + row["exported_guid"] + ", type: 3}").encode()
    new = ("m_Script: {fileID: 11500000, guid: " + row["target_guid"] + ", type: 3}").encode()
    assert content.count(old) == 1
    return content.replace(old, new)


class RuntimeConfigurationDocumentTests(unittest.TestCase):
    def test_observed_shapes_change_only_the_script_line(self):
        for row in CONFIGURATIONS:
            with self.subTest(owner=row["full_name"]):
                content = configuration(row)
                actual, count = rewrite_configuration_pointers(content, CONFIGURATIONS)
                self.assertEqual(1, count)
                self.assertEqual(swapped(content, row), actual)
                self.assertEqual((swapped(content, row), 1), rewrite_prepared_script_pointers(content, CONFIGURATIONS))

    def test_unprofiled_or_reordered_nested_members_are_rejected(self):
        for replace in (("    m_enabled: 1\n", ""),
                        ("    m_enabled: 1\n    m_breadcrumbMessage: Low Memory Warning\n",
                         "    m_breadcrumbMessage: Low Memory Warning\n    m_enabled: 1\n"),
                        ("    m_triggerResourcesUnloadAssets: 1\n", "    m_triggerResourcesUnloadAssets: 1\n    m_extra: 1\n"),
                        ("    m_enabled: 1\n", "    m_enabled: 2\n"),
                        ("    m_minimumLogIntervalSeconds: 5\n", "    m_minimumLogIntervalSeconds: nan\n"),
                        ("    m_enabled: 1\n", "      m_enabled: 1\n"),
                        ("  m_lowMemoryConfiguration:\n", "  m_lowMemoryConfiguration: 1\n")):
            with self.subTest(replace=replace):
                with self.assertRaises(ValueError):
                    rewrite_configuration_pointers(configuration(CORE, replace), CONFIGURATIONS)
        # A nested block under a field the owner does not profile as nested.
        with self.assertRaises(ValueError):
            rewrite_configuration_pointers(configuration(CORE, ("  m_logInPlaceOfException: 0\n",
                                                                "  m_logInPlaceOfException:\n    m_value: 0\n")), CONFIGURATIONS)
        with self.assertRaises(ValueError):
            rewrite_configuration_pointers(configuration(TIME, ("  m_unityGlobalTime: " + pointer(12) + "\n",
                                                                "  m_unityGlobalTime:\n    fileID: 0\n")), CONFIGURATIONS)

    def test_scalar_kinds_are_bounded(self):
        cases = ((TIME, ("m_defaultTimescale: 1\n", "m_defaultTimescale: 1e39\n")),
                 (TIME, ("m_defaultTimescale: 1\n", "m_defaultTimescale: one\n")),
                 (TIME, ("m_generatesLookupStrings: 0\n", "m_generatesLookupStrings: false\n")),
                 (NAVIGATION, ("m_selectionUpInput: -242970151\n", "m_selectionUpInput: 4294967296\n")),
                 (ANALYTICS, ("https://analytics-receiver.example.com/receiver", "http://analytics-receiver.example.com/receiver")),
                 (ANALYTICS, ("https://analytics-receiver.example.com/receiver", "https://example.com/r?q=1")),
                 (ANALYTICS, ("m_gameID: sdt-dev\n", "m_gameID: 'sdt-dev'\n")),
                 (ANALYTICS, ("m_maxSendAttempts: 3\n", "m_maxSendAttempts: 3.5\n")))
        for row, replace in cases:
            with self.subTest(owner=row["full_name"], replace=replace):
                with self.assertRaises(ValueError):
                    rewrite_configuration_pointers(configuration(row, replace), CONFIGURATIONS)

    def test_a_local_base_asset_is_accepted_only_for_the_analytics_owner(self):
        self.assertEqual(1, rewrite_configuration_pointers(configuration(ANALYTICS), CONFIGURATIONS)[1])
        for row in (TIME, CORE, NAVIGATION):
            with self.subTest(owner=row["full_name"]):
                with self.assertRaises(ValueError):
                    rewrite_configuration_pointers(configuration(row, ("m_baseAsset: {fileID: 0}\n",
                                                                       "m_baseAsset: {fileID: 11400000}\n")), CONFIGURATIONS)
        with self.assertRaises(ValueError):
            rewrite_configuration_pointers(configuration(ANALYTICS, ("m_baseAsset: {fileID: 11400000}\n",
                                                                     "m_baseAsset: {fileID: 11400001}\n")), CONFIGURATIONS)

    def test_field_set_and_order_remain_exact(self):
        for row, replace in ((TIME, ("  m_generatesLookupStrings: 0\n", "")),
                             (NAVIGATION, ("  m_selectionLeftInput: 707471584\n  m_selectionRightInput: -1097466484\n",
                                           "  m_selectionRightInput: -1097466484\n  m_selectionLeftInput: 707471584\n")),
                             (ANALYTICS, ("  m_persistentEventIndex: 1\n", "  m_persistentEventIndex: 1\n  m_extra: 1\n"))):
            with self.subTest(owner=row["full_name"]):
                with self.assertRaises(ValueError):
                    rewrite_configuration_pointers(configuration(row, replace), CONFIGURATIONS)


