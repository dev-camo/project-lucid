        public static MemberInfo GetMemberInfo(Type type, string memberName, BindingFlags flags = BindingFlags.Instance | BindingFlags.Public | BindingFlags.FlattenHierarchy)
        {
            MemberInfo member;
            if (cachedMembers[type].TryGetValue(memberName, out member)) return member;
            int count = 0;
            foreach (FieldInfo field in type.GetFields(flags)) if (field.Name == memberName) ++count;
            FieldInfo foundField = type.GetField(memberName, count == 1 ? flags : flags | BindingFlags.DeclaredOnly);
            if (foundField != null)
            {
                cachedMembers[type][memberName] = foundField;
                return foundField;
            }
            count = 0;
            foreach (PropertyInfo property in type.GetProperties(flags)) if (property.Name == memberName) ++count;
            PropertyInfo foundProperty = type.GetProperty(memberName, count == 1 ? flags : flags | BindingFlags.DeclaredOnly);
            if (foundProperty != null)
            {
                cachedMembers[type][memberName] = foundProperty;
                return foundProperty;
            }
            MethodInfo[] methods;
            if (!cachedMethods.TryGetValue(type, out methods))
            {
                methods = type.GetMethods(flags);
                cachedMethods[type] = methods;
            }
            foreach (MethodInfo method in methods)
            {
                if (method.Name == memberName)
                {
                    cachedMembers[type][memberName] = method;
                    return method;
                }
            }
            return null;
        }

        public static List<MemberInfo> SettableMembers(Type type, BindingFlags flags = BindingFlags.Instance | BindingFlags.Public | BindingFlags.FlattenHierarchy)
        {
            List<MemberInfo> members = new List<MemberInfo>();
            List<PropertyInfo> properties = new List<PropertyInfo>();
            foreach (MemberInfo member in type.GetMembers(flags))
            {
                MemberInfo resolved = GetMemberInfo(type, member.Name, flags);
                if (!members.Contains(resolved) && UnderlyingSetType(resolved) != null) members.Add(resolved);
                PropertyInfo property = member as PropertyInfo;
                if (property != null) properties.Add(property);
            }
            foreach (PropertyInfo property in properties)
            {
                if (property.CanWrite)
                {
                    string setterName = "set_" + property.Name;
                    members.RemoveAll(m => m.Name == setterName);
                }
            }
            members.RemoveAll(m => m.IsDefined<ObsoleteAttribute>() || m.IsDefined<HideInBinder>());
            return members;
        }

        public static List<MemberInfo> GettableBindableMembers(Type type, BindingFlags flags = BindingFlags.Instance | BindingFlags.Public | BindingFlags.FlattenHierarchy)
        {
