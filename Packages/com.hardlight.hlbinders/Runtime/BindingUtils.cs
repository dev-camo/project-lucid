        public static void SetMemberValue(MemberInfo member, object target, object value)
        {
            if (SetFieldValue(member as FieldInfo, target, value)) return;
            if (SetPropertyValue(member as PropertyInfo, target, value)) return;
            SetMemberValue(member as MethodInfo, target, value);
        }

        public static bool SetFieldValue(FieldInfo field, object target, object value)
        {
            if (field == null || field.IsInitOnly) return false;
            field.SetValue(target, value);
            return true;
        }

        public static bool SetPropertyValue(PropertyInfo property, object target, object value)
        {
            if (property == null || !property.CanWrite) return false;
            try
            {
                property.SetValue(target, value, null);
            }
            catch (TargetInvocationException exception)
            {
                if (exception.InnerException != null)
                {
                    HLOutput.LogError(exception.InnerException.GetType() + "\n" + exception.InnerException.Message);
                    throw exception;
                }
            }
            return true;
        }

        public static bool SetMethodValue(MethodInfo method, object target, object value)
        {
            if (method == null || method.ContainsGenericParameters || !MethodCanBeInvokedWithSingleParameter(method) || method.ReturnType != typeof(void)) return false;
            InvokeMethodHandlingOptionalParameters(method, target, value);
            return true;
        }

        private static bool MethodCanBeInvokedWithSingleParameter(MethodInfo method)
        {
            ParameterInfo[] parameters = method.GetParameters();
            return parameters.Length > 0 && (parameters.Length < 2 || parameters[1].IsOptional);
        }

        private static object[] s_methodInvokeArray = new object[1];
        private static List<object> s_methodInvokeList = new List<object>();

        private static void InvokeMethodHandlingOptionalParameters(MethodInfo method, object target, object parameter)
        {
            try
            {
                ParameterInfo[] parameters = method.GetParameters();
                if (parameters.Length == 1)
                {
                    s_methodInvokeArray[0] = parameter;
                    method.Invoke(target, s_methodInvokeArray);
                }
                else
                {
                    s_methodInvokeList.Clear();
                    s_methodInvokeList.Add(parameter);
                    for (int i = 1; i < parameters.Length; ++i) s_methodInvokeList.Add(parameters[i].DefaultValue);
                    method.Invoke(target, s_methodInvokeList.ToArray());
                }
            }
            catch (TargetInvocationException exception)
            {
                HLOutput.LogError(exception.InnerException.ToString());
            }
        }

        public static object GetMemberValue(MemberInfo member, object target)
        {
            FieldInfo field = member as FieldInfo;
            if (field != null) return field.GetValue(target);
            PropertyInfo property = member as PropertyInfo;
            if (property != null) return GetPropertyValue(property, target);
            MethodInfo method = member as MethodInfo;
            return method != null ? GetMethodValue(method, target) : null;
        }

        public static object GetPropertyValue(PropertyInfo property, object target)
        {
            return property.CanRead ? property.GetValue(target, null) : null;
        }

        private static object[] emptyMethodInvokeArray = new object[0];

        public static object GetMethodValue(MethodInfo method, object target)
        {
            return method.GetParameters().Length == 0 && method.ReturnType != typeof(void) ? method.Invoke(target, emptyMethodInvokeArray) : null;
        }

        public static Type GetBindableDictionaryValueType(Type memberType, ref Type keyType)
        {
            if (memberType == null)
            {
                keyType = null;
                return null;
            }
            DictionaryInfo info;
            if (!cachedDictionaryInfo.TryGetValue(memberType, out info))
            {
                info = default(DictionaryInfo);
                Type dictionaryType = null;
                if (memberType.IsGenericType && memberType.GetGenericTypeDefinition() == typeof(IDictionary<,>)) dictionaryType = memberType;
                else
                {
                    foreach (Type interfaceType in memberType.GetInterfaces())
                    {
                        if (interfaceType.IsGenericType && interfaceType.GetGenericTypeDefinition() == typeof(IDictionary<,>))
                        {
                            dictionaryType = interfaceType;
                            break;
                        }
                    }
                }
                if (dictionaryType != null)
                {
                    Type[] arguments = dictionaryType.GetGenericArguments();
                    if (arguments[0].IsEnum && arguments[1].IsGenericType && arguments[1].GetGenericTypeDefinition() == typeof(Bindable<>))
                    {
                        info.keyType = arguments[0];
                        info.valueType = arguments[1].GetGenericArguments()[0];
                    }
                }
                cachedDictionaryInfo[memberType] = info;
            }
            keyType = info.keyType;
            return info.valueType;
        }

        public static Type GetBindableValueType(Type memberType)
        {
            if (memberType == null || !memberType.IsGenericType || memberType.GetGenericTypeDefinition() != typeof(Bindable<>)) return null;
            return memberType.GetGenericArguments()[0];
        }

        public static Type UnifiedBindableValueType(Type memberType)
        {
            Type keyType = null;
            return UnifiedBindableValueType(memberType, ref keyType);
        }

        public static Type UnifiedBindableValueType(Type memberType, ref Type keyType)
        {
            Type valueType = GetBindableDictionaryValueType(memberType, ref keyType);
            return valueType ?? GetBindableValueType(memberType);
        }

