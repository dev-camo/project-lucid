        public static Type UnderlyingGetType(MemberInfo member)
        {
            FieldInfo field = member as FieldInfo;
            if (field != null) return field.FieldType;
            PropertyInfo property = member as PropertyInfo;
            if (property != null && property.CanRead) return property.PropertyType;
            MethodInfo method = member as MethodInfo;
            if (method != null && method.GetParameters().Length == 0 && method.ReturnType != typeof(void)) return method.ReturnType;
            return null;
        }

        public static Type UnderlyingPropertyGetType(PropertyInfo property)
        {
            return property.CanRead ? property.PropertyType : null;
        }

        public static Type UnderlyingMethodGetType(MethodInfo method)
        {
            Type returnType = method.ReturnType;
            return method.GetParameters().Length == 0 && returnType != typeof(void) ? returnType : null;
        }

        public static Type UnderlyingSetType(MemberInfo member)
        {
            FieldInfo field = member as FieldInfo;
            if (field != null && !field.IsInitOnly) return field.FieldType;
            PropertyInfo property = member as PropertyInfo;
            if (property != null && property.CanWrite) return property.PropertyType;
            MethodInfo method = member as MethodInfo;
            if (method != null && !method.ContainsGenericParameters && MethodCanBeInvokedWithSingleParameter(method) && method.ReturnType == typeof(void)) return method.GetParameters()[0].ParameterType;
            return null;
        }

