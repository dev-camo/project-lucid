using System;
using System.Collections.Generic;
using Hardlight;
using UnityEngine;

namespace ProjectLucid.Verification
{
    // Owned HLHaptics cases checked against shipped metadata rows and x86-64 bodies.
    // Every manager stays on an inactive object, so Awake never registers it.
    public static class HLHapticsEventContractVerification
    {
        static void Require(bool ok, string message) { if (!ok) throw new InvalidOperationException(message); }

        // Field rows VibrationEventData 0x04000001 m_vibrationEvent, 0x04000002 m_vibrationEvents
        // and Vibrations 0x04000003 m_delay, 0x04000004 m_vibrationType, 0x04000005 m_repeat.
        // HLAutoGenerated enum defaults: VibrationEvent DefaultSelection 0x04000368 = 890026456,
        // LongPressSelection 0x04000369 = -1688333712; VibrationType ImpactLight 0x0400036c =
        // 2110532147, None 0x0400036e = -1225125244, Selection 0x04000372 = 764997063.
        public static void JsonUsesOriginalFieldOrderAndEnumLiterals()
        {
            var owned = new List<UnityEngine.Object>();
            try
            {
                var data = ScriptableObject.CreateInstance<VibrationEventData>(); owned.Add(data);
                data.m_vibrationEvent = VibrationEvent.LongPressSelection;
                data.m_vibrationEvents = new[] { new VibrationEventData.Vibrations { m_delay = 0.5f, m_vibrationType = VibrationType.ImpactLight, m_repeat = 2f } };
                string json = JsonUtility.ToJson(data);
                Require(json.Contains("\"m_vibrationEvent\":-1688333712"), "original LongPressSelection literal: " + json);
                Require(json.Contains("\"m_vibrationType\":2110532147"), "original ImpactLight literal: " + json);
                Require(Before(json, "\"m_vibrationEvent\":", "\"m_vibrationEvents\":"), "original outer field order: " + json);
                Require(Before(json, "\"m_delay\":", "\"m_vibrationType\":") && Before(json, "\"m_vibrationType\":", "\"m_repeat\":"), "original entry field order: " + json);

                // Authored payloads carry raw Int32 literals; they must land on the original names.
                var authored = ScriptableObject.CreateInstance<VibrationEventData>(); owned.Add(authored);
                JsonUtility.FromJsonOverwrite("{\"m_vibrationEvent\":890026456,\"m_vibrationEvents\":[{\"m_delay\":0.25,\"m_vibrationType\":764997063,\"m_repeat\":3.0},{\"m_delay\":0.0,\"m_vibrationType\":-1225125244,\"m_repeat\":0.0}]}", authored);
                Require(authored.m_vibrationEvent == VibrationEvent.DefaultSelection, "authored DefaultSelection literal");
                Require(authored.m_vibrationEvents != null && authored.m_vibrationEvents.Length == 2, "authored entries");
                VibrationEventData.Vibrations first = authored.m_vibrationEvents[0], second = authored.m_vibrationEvents[1];
                Require(first.m_vibrationType == VibrationType.Selection && first.m_delay == 0.25f && first.m_repeat == 3f, "authored first entry fields");
                Require(second.m_vibrationType == VibrationType.None && second.m_delay == 0f && second.m_repeat == 0f, "authored second entry fields");
            }
            finally { foreach (UnityEngine.Object value in owned) UnityEngine.Object.DestroyImmediate(value); }
        }

        static bool Before(string text, string first, string second)
        {
            int a = text.IndexOf(first, StringComparison.Ordinal), b = text.IndexOf(second, StringComparison.Ordinal);
            return a >= 0 && b >= 0 && a < b;
        }

        // TriggerEvent(VibrationEvent) 0x0600000d, x86-64 0x1a195e0: with IsAvailable [+0x2a]
        // or settings [+0x29] false it tests None (0x1a19609) before the debug flag [+0x28]
        // (0x1a19611), and only then loads m_vibrationEventDefinitions (0x1a1961c).
        public static void UnavailableTriggerTestsNoneBeforeDebugFlagAndDefinitions()
        {
            var host = new GameObject("HLHaptics owned unavailable trigger fixture");
            try
            {
                host.SetActive(false);
                var manager = host.AddComponent<VibrationManager>();
                Require(!manager.IsAvailable && !manager.VibrationEnabledInSettings, "inactive manager stays unavailable");
                Require(typeof(VibrationManager).GetField("m_vibrationEventDefinitions", System.Reflection.BindingFlags.NonPublic | System.Reflection.BindingFlags.Instance).GetValue(manager) == null, "no authored definitions");

                // Debug off: a real event returns before the null definition array is read.
                manager.TriggerEvent(VibrationEvent.DefaultSelection);
                JsonUtility.FromJsonOverwrite("{\"m_debugInEditor\":true}", manager);
                // Debug on: None still returns first; any other event reaches the array.
                manager.TriggerEvent(VibrationEvent.None);
                Exception observed = null;
                try { manager.TriggerEvent(VibrationEvent.DefaultSelection); } catch (Exception e) { observed = e; }
                Require(observed is NullReferenceException, "debug flag opens the definition scan; observed " + (observed == null ? "none" : observed.GetType().ToString()));
                manager.SetVibrationFromSettings(true);
                manager.TriggerEvent(VibrationEvent.None);
                Require(!manager.IsAvailable, "settings do not make the inactive manager available");
            }
            finally { UnityEngine.Object.DestroyImmediate(host); }
        }
    }
}
