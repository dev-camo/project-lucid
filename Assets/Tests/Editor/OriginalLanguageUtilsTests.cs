    private const BindingFlags Declared = BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly;

    [Test]
    public void LanguageUtilsRetainsWholeAuthoredTypeFieldsAndOrderedAnnotations()
    {
        Type type = typeof(LanguageUtils);
        Assert.AreEqual("Hardlight.Localisation.LanguageUtils", type.FullName);
        Assert.AreEqual("HLLocalisation.Runtime", type.Assembly.GetName().Name);
        Assert.AreEqual(1048577, (int)type.Attributes);
        Assert.AreEqual(typeof(MonoSingleton<LanguageUtils>), type.BaseType);
        CollectionAssert.AreEqual(new[] { typeof(ISystem) }, type.GetInterfaces());
        Assert.AreEqual(0, type.GetGenericArguments().Length);
        Assert.AreEqual(0, type.GetNestedTypes(Declared).Length);
        Assert.AreEqual(0, type.GetProperties(Declared).Length);
        Assert.AreEqual(0, type.GetEvents(Declared).Length);
        IList<CustomAttributeData> options = type.GetCustomAttributesData();
        Assert.AreEqual(2, options.Count);
        for (int i = 0; i < options.Count; i++)
        {
            Attribute(options[i], typeof(Il2CppSetOptionAttribute), new[] { typeof(Option), typeof(object) });
            Assert.AreEqual(typeof(Option), options[i].ConstructorArguments[0].ArgumentType);
            Assert.AreEqual(i == 0 ? 2 : 1, options[i].ConstructorArguments[0].Value);
            Assert.AreEqual(typeof(bool), options[i].ConstructorArguments[1].ArgumentType);
            Assert.AreEqual(false, options[i].ConstructorArguments[1].Value);
        }

        string[] names = { "separatorID", "decimalID", "thousandsID", "millionsID", "billionsID", "thousandsFormatString", "millionsFormatString", "billionsFormatString", "m_numberFormatter" };
        FieldInfo[] fields = type.GetFields(Declared).OrderBy(field => field.MetadataToken).ToArray();
        CollectionAssert.AreEqual(names, fields.Select(field => field.Name).ToArray());
        for (int i = 0; i < fields.Length; i++)
        {
            FieldInfo field = fields[i];
            Assert.AreEqual(type, field.DeclaringType);
            Assert.AreEqual(1, (int)field.Attributes);
            Assert.AreEqual(i < 5 ? typeof(Strings) : i < 8 ? typeof(string) : typeof(NumberFormatInfo), field.FieldType);
            Assert.IsFalse(field.IsLiteral);
            Assert.IsFalse(field.IsInitOnly);
            Assert.IsFalse(field.IsStatic);
            IList<CustomAttributeData> rows = field.GetCustomAttributesData();
            Assert.AreEqual(i < 5 ? 2 : 0, rows.Count);
            if (i < 5)
            {
                int serialized = i == 0 ? 0 : 1;
                Attribute(rows[serialized], typeof(SerializeField), Type.EmptyTypes);
                CustomAttributeData hash = rows[1 - serialized];
                Attribute(hash, typeof(HashEnumAttribute), new[] { typeof(Type) });
                Assert.AreEqual(typeof(Type), hash.ConstructorArguments[0].ArgumentType);
                Assert.AreEqual(typeof(Strings), hash.ConstructorArguments[0].Value);
                Assert.AreEqual("HLAutoGenerated", typeof(Strings).Assembly.GetName().Name);
            }
        }
        // Field initializers are instance construction behavior, not reflected literal defaults.
        // No LanguageUtils, singleton, table, formatter, or attribute instance is constructed here.
    }

    [Test]
    public void LanguageUtilsRetainsWholeOverloadsPrivateInstanceLeavesAndTypedDefaults()
    {
        Type type = typeof(LanguageUtils);
        MethodInfo[] methods = type.GetMethods(Declared).OrderBy(method => method.MetadataToken).ToArray();
        CollectionAssert.AreEqual(new[] { "FormatNumber", "FormatNumber", "FormatNumber", "InitialiseNumberFormatter", "GenerateAbbreviatedValue" }, methods.Select(method => method.Name).ToArray());
        Type[][] signatures = {
            new[] { typeof(long) }, new[] { typeof(double) },
            new[] { typeof(double), typeof(int), typeof(bool), typeof(bool) },
            Type.EmptyTypes, new[] { typeof(double), typeof(string).MakeByRefType() }
        };
        string[][] names = {
            new[] { "numberToFormat" }, new[] { "numberToFormat" },
            new[] { "numberToFormat", "decimalPlaces", "ignoreZeroDecimal", "abbreviate" },
            new string[0], new[] { "numberToFormat", "formatString" }
        };
        int count = 0;
        for (int i = 0; i < methods.Length; i++)
        {
            MethodInfo method = methods[i];
            Assert.AreEqual(type, method.DeclaringType);
            Assert.AreEqual(i < 3 ? 134 : 129, (int)method.Attributes);
            Assert.AreEqual(0, (int)method.GetMethodImplementationFlags());
            Assert.AreEqual(i < 3 ? typeof(string) : i == 3 ? typeof(void) : typeof(double), method.ReturnType);
            Assert.IsFalse(method.IsStatic);
            Assert.IsFalse(method.IsGenericMethod);
            Assert.AreEqual(0, method.GetCustomAttributesData().Count);
            Assert.AreEqual(0, method.ReturnParameter.GetCustomAttributesData().Count);
            ParameterInfo[] parameters = method.GetParameters();
            CollectionAssert.AreEqual(signatures[i], parameters.Select(parameter => parameter.ParameterType).ToArray());
            CollectionAssert.AreEqual(names[i], parameters.Select(parameter => parameter.Name).ToArray());
            count += parameters.Length;
            for (int j = 0; j < parameters.Length; j++)
            {
                ParameterInfo parameter = parameters[j];
                bool optional = i == 2 && j >= 2;
                bool output = i == 4 && j == 1;
                Assert.AreEqual(j, parameter.Position);
                Assert.AreEqual(optional ? 4112 : output ? 2 : 0, (int)parameter.Attributes);
                Assert.AreEqual(optional, parameter.HasDefaultValue);
                Assert.AreEqual(optional, parameter.IsOptional);
                Assert.AreEqual(output, parameter.IsOut);
                Assert.IsFalse(parameter.IsIn);
                if (optional)
                {
                    Assert.AreEqual(typeof(bool), parameter.DefaultValue.GetType());
                    Assert.AreEqual(false, parameter.DefaultValue);
                }
                // Mono projects Optional/Out bits as pseudoattributes; the stored shipping rows are empty.
                IList<CustomAttributeData> rows = parameter.GetCustomAttributesData();
                Assert.AreEqual(optional || output ? 1 : 0, rows.Count);
                if (rows.Count != 0)
                    Attribute(rows[0], optional ? typeof(OptionalAttribute) : typeof(OutAttribute), Type.EmptyTypes);
            }
        }
        Assert.AreEqual(8, count);
        ConstructorInfo[] constructors = type.GetConstructors(Declared);
        Assert.AreEqual(1, constructors.Length);
        Assert.AreEqual(6278, (int)constructors[0].Attributes);
        Assert.AreEqual(0, (int)constructors[0].GetMethodImplementationFlags());
        Assert.AreEqual(0, constructors[0].GetParameters().Length);
        Assert.AreEqual(0, constructors[0].GetCustomAttributesData().Count);
        Assert.IsNull(type.TypeInitializer);
        // The private leaves are deliberately not invoked: they require the original instance caches.
        // Formatting, signed thresholds, decimals and NaN retain their separate source/native evidence.
    }

    [Test]
    public void LanguageUtilsInactiveConstructionRetainsOriginalNoneAndNullCaches()
    {
        WithInactiveLanguageUtils(component =>
        {
            using (var serialized = new UnityEditor.SerializedObject(component))
            {
                serialized.Update();
                foreach (string name in new[] { "separatorID", "decimalID", "thousandsID", "millionsID", "billionsID" })
                {
                    UnityEditor.SerializedProperty field = serialized.FindProperty(name);
                    Assert.IsNotNull(field, name);
                    Assert.AreEqual(UnityEditor.SerializedPropertyType.Enum, field.propertyType);
                    Assert.AreEqual(-1225125244, field.intValue);
                }
                foreach (string name in CacheNames)
                    Assert.IsNull(serialized.FindProperty(name), name);
            }
            AssertCachesAreNull(component);
        });
    }

    [Test]
    public void LanguageUtilsOwnedAbbreviationRetainsSignedStrictThresholdsAndNullOutputs()
    {
        WithInactiveLanguageUtils(component =>
        {
            double[] inputs = { -1000000000000d, -1000000d, -1d, 0d, 999999d, 1000000d, 999999999d, 1000000000d, 2500000000d };
            double[] divisors = { 1000d, 1000d, 1000d, 1000d, 1000d, 1000000d, 1000000d, 1000000000d, 1000000000d };
            for (int i = 0; i < inputs.Length; i++)
            {
                double result = AbbreviatedValue(component, inputs[i]);
                Assert.AreEqual(inputs[i] / divisors[i], result, "input " + inputs[i]);
                AssertCachesAreNull(component);
            }
        });
    }

    [Test]
    public void LanguageUtilsOwnedAbbreviationRetainsNonfiniteAndSignedZeroResults()
    {
        WithInactiveLanguageUtils(component =>
        {
            Assert.IsTrue(double.IsNaN(AbbreviatedValue(component, double.NaN)));
            Assert.AreEqual(double.PositiveInfinity, AbbreviatedValue(component, double.PositiveInfinity));
            Assert.AreEqual(double.NegativeInfinity, AbbreviatedValue(component, double.NegativeInfinity));
            double negativeZero = BitConverter.Int64BitsToDouble(long.MinValue);
            Assert.AreEqual(long.MinValue, BitConverter.DoubleToInt64Bits(AbbreviatedValue(component, negativeZero)));
            Assert.AreEqual(0L, BitConverter.DoubleToInt64Bits(AbbreviatedValue(component, 0d)));
            AssertCachesAreNull(component);
            // Null caches cannot distinguish the NaN format branch; the sentinel pairing case pins it.
            // This helper does not reach flooring, integer conversions, Mathf.Pow or exp10f.
        });
    }

    // 0x0600002a x86-64 0x1a35560: below 1e6 stores the cache at +0x38, below 1e9
    // the one at +0x40, otherwise +0x48; both ucomisd/jbe tests fall through on
    // NaN to the last branch. The three caches follow declaration order
    // (thousands, millions, billions), so distinct sentinels pin each pairing.
    // Mutations caught: swapping any two format assignments, or routing NaN to
    // the thousands branch (e.g. testing >= 1e6 first).
    [Test]
    public void LanguageUtilsOwnedAbbreviationPairsEachBranchWithItsFormatCache()
    {
        WithInactiveLanguageUtils(component =>
        {
            const string thousands = "thousands sentinel {0}", millions = "millions sentinel {0}", billions = "billions sentinel {0}";
            SetCache(component, "thousandsFormatString", thousands);
            SetCache(component, "millionsFormatString", millions);
            SetCache(component, "billionsFormatString", billions);
            double[] inputs = { -1000000000000d, -1d, 999999d, 1000000d, 999999999d, 1000000000d, double.PositiveInfinity, double.NegativeInfinity, double.NaN };
            string[] formats = { thousands, thousands, thousands, millions, millions, billions, billions, thousands, billions };
            for (int i = 0; i < inputs.Length; i++)
            {
                string format;
                AbbreviatedValue(component, inputs[i], out format);
                Assert.AreSame(formats[i], format, "input " + inputs[i]);
            }
            Assert.AreSame(thousands, typeof(LanguageUtils).GetField("thousandsFormatString", Declared).GetValue(component));
            Assert.AreSame(millions, typeof(LanguageUtils).GetField("millionsFormatString", Declared).GetValue(component));
            Assert.AreSame(billions, typeof(LanguageUtils).GetField("billionsFormatString", Declared).GetValue(component));
            Assert.IsNull(typeof(LanguageUtils).GetField("m_numberFormatter", Declared).GetValue(component));
        });
    }

    private static void SetCache(LanguageUtils component, string name, string value)
    {
        FieldInfo field = typeof(LanguageUtils).GetField(name, Declared);
        Assert.IsNotNull(field, name);
        field.SetValue(component, value);
    }

    private static readonly string[] CacheNames = { "thousandsFormatString", "millionsFormatString", "billionsFormatString", "m_numberFormatter" };

    private static void AssertCachesAreNull(LanguageUtils component)
    {
        foreach (string name in CacheNames)
        {
            FieldInfo field = typeof(LanguageUtils).GetField(name, Declared);
            Assert.IsNotNull(field, name);
            Assert.IsNull(field.GetValue(component), name);
        }
    }

    private static double AbbreviatedValue(LanguageUtils component, double value)
    {
        string format;
        double result = AbbreviatedValue(component, value, out format);
        Assert.IsNull(format);
        return result;
    }

    private static double AbbreviatedValue(LanguageUtils component, double value, out string format)
    {
        MethodInfo method = typeof(LanguageUtils).GetMethod("GenerateAbbreviatedValue", Declared, null,
            new[] { typeof(double), typeof(string).MakeByRefType() }, null);
        Assert.IsNotNull(method);
        Assert.IsFalse(method.IsStatic);
        Assert.IsTrue(method.IsPrivate);
        object[] arguments = { value, null };
        double result = (double)method.Invoke(component, arguments);
        format = (string)arguments[1];
        return result;
    }

    private static void WithInactiveLanguageUtils(Action<LanguageUtils> action)
    {
        LanguageUtils baseline = MonoSingleton<LanguageUtils>.Instance;
        GameObject root = null;
        try
        {
            root = new GameObject("Owned inactive LanguageUtils numeric leaf");
            root.SetActive(false);
            LanguageUtils component = root.AddComponent<LanguageUtils>();
            Assert.IsFalse(root.activeSelf);
            Assert.IsFalse(root.activeInHierarchy);
            Assert.AreSame(root, component.gameObject);
            Assert.AreSame(baseline, MonoSingleton<LanguageUtils>.Instance);
            action(component);
            Assert.IsFalse(root.activeSelf);
            Assert.IsFalse(root.activeInHierarchy);
            Assert.AreSame(baseline, MonoSingleton<LanguageUtils>.Instance);
        }
        finally
        {
            try { if (!ReferenceEquals(root, null)) UnityEngine.Object.DestroyImmediate(root); }
            finally { Assert.AreSame(baseline, MonoSingleton<LanguageUtils>.Instance); }
        }
    }

    private static void Attribute(CustomAttributeData row, Type attributeType, Type[] parameters)
    {
        Assert.AreEqual(attributeType, row.AttributeType);
        Assert.AreEqual(attributeType, row.Constructor.DeclaringType);
        CollectionAssert.AreEqual(parameters, row.Constructor.GetParameters().Select(parameter => parameter.ParameterType).ToArray());
        Assert.AreEqual(parameters.Length, row.ConstructorArguments.Count);
        Assert.AreEqual(0, row.NamedArguments.Count);
    }
}
