using System;
using System.Linq;
using System.Reflection;
using Hardlight;
using NUnit.Framework;
using Unity.IL2CPP.CompilerServices;
using UnityEngine;
using Object = UnityEngine.Object;

namespace ProjectLucid.Tests
{
    // Behaviour specification for Hardlight.UISystemConfiguration (HLUnityUI.Runtime,
    // TypeDefIndex 11853, MethodDefs 0x060000c7..0x060000dc) and the field-only
    // Hardlight.NamedUnityEvent (TypeDefIndex 12040, .ctor 0x060005d1), written from
    // dump.cs and the shipped x86-64 bodies. Each case owns the instances it creates.
    [TestFixture]
    public sealed class OriginalUISystemConfigurationTests
    {
        const BindingFlags InstanceFields = BindingFlags.Instance | BindingFlags.NonPublic | BindingFlags.Public | BindingFlags.DeclaredOnly;
        static readonly Type Subject = typeof(UISystemConfiguration);

        static void Set(object target, string name, object value) => Subject.GetField(name, BindingFlags.Instance | BindingFlags.NonPublic).SetValue(target, value);

        static string AttributeRow(CustomAttributeData attribute) =>
            attribute.AttributeType.Name + "(" + string.Join(",", attribute.ConstructorArguments.Select(a => a.Value)) + ")";

        static int[] Il2CppOptions(MemberInfo member) =>
            member.GetCustomAttributesData()
                .Where(a => a.AttributeType == typeof(Il2CppSetOptionAttribute))
                .Select(a => (int)a.ConstructorArguments[0].Value).ToArray();

        static UISystemConfiguration Create() => ScriptableObject.CreateInstance<UISystemConfiguration>();

        // ---- declaration --------------------------------------------------------

        // dump.cs TypeDefIndex 11853: sealed SingleScriptableObject with three constants
        // and twenty serialized fields in this order, including the original's second
        // "GUI Scenes" header and the "Additonal" spelling.
        [Test]
        public void DeclarationKeepsTheOriginalConstantsFieldsAndHeaders()
        {
            Assert.That(Subject.IsSealed, Is.True);
            Assert.That(Subject.BaseType, Is.EqualTo(typeof(SingleScriptableObject)));
            Assert.That(Il2CppOptions(Subject), Is.EqualTo(new[] { (int)Option.NullChecks, (int)Option.ArrayBoundsChecks }));

            Assert.That(UISystemConfiguration.TemporaryUICameraName, Is.EqualTo("[AUTOGENERATED] Temporary UI Camera prefab"));
            Assert.That(UISystemConfiguration.DefaultFileName, Is.EqualTo("UISystemConfiguration"));
            Assert.That(UISystemConfiguration.NumberOfBuiltInLayers, Is.EqualTo(8));

            FieldInfo[] fields = Subject.GetFields(InstanceFields);
            Assert.That(fields.Select(f => f.Name + ":" + f.FieldType.Name), Is.EqualTo(new[] {
                "m_autoGeneratedCodeFolder:String", "m_autoGeneratedUINamespace:String", "m_autoGeneratedUtilsNamespace:String",
                "m_autoGeneratedUIEnumComparerClassName:String", "m_tagNamesClassName:String", "m_layerNamesClassName:String",
                "m_uiSortingLayerNamesClassName:String", "m_sceneNamesClassName:String", "m_pageTypeIdentifierEnumSuffix:String",
                "m_subPageTypeIdentifierEnumSuffix:String", "m_projectsAssetsFolderPath:String", "m_rootSceneFolderPath:String",
                "m_coreGUISceneFolderAdditonalPath:String", "m_uiCameraPrefab:GameObject", "m_enforcedTags:String[]",
                "m_enforcedLayers:String[]", "m_enforcedSortingLayers:String[]", "m_defaultReferenceResolutionForCanvasScaler:Vector2",
                "m_skipSceneValidationEventSystem:Boolean", "m_skipSceneValidationGUIRootTag:Boolean" }));
            Assert.That(fields.All(f => f.IsPrivate && f.IsDefined(typeof(SerializeField), false)), Is.True);

            string[] Rows(string name) => Subject.GetField(name, BindingFlags.Instance | BindingFlags.NonPublic)
                .GetCustomAttributesData().Select(AttributeRow).ToArray();
            Assert.That(Rows("m_autoGeneratedCodeFolder"), Is.EqualTo(new[] { "SerializeField()", "SpaceAttribute()", "HeaderAttribute(Auto Generated Code)" }));
            Assert.That(Rows("m_projectsAssetsFolderPath"), Is.EqualTo(new[] { "HeaderAttribute(GUI Scenes)", "SpaceAttribute()", "SerializeField()" }));
            Assert.That(Rows("m_enforcedTags"), Is.EqualTo(new[] { "HeaderAttribute(Enforced Tags, Layers and Sorting Layers)", "SpaceAttribute()", "SerializeField()" }));
            Assert.That(Rows("m_defaultReferenceResolutionForCanvasScaler"), Is.EqualTo(new[] { "SpaceAttribute()", "SerializeField()", "HeaderAttribute(GUI Scenes)" }));
            Assert.That(Rows("m_skipSceneValidationEventSystem"), Is.EqualTo(new[] { "HeaderAttribute(Validation)", "SpaceAttribute()", "SerializeField()" }));
            Assert.That(Rows("m_uiCameraPrefab"), Is.EqualTo(new[] { "SerializeField()" }));
        }

        // ---- .ctor 0x060000dc (0x1b3f350) ---------------------------------------

        // The constructor stores the literals at 0x1b3f569..0x1b3f688, builds the three
        // arrays (3, 4 and 0x16 entries) in this order, writes the packed qword
        // 0x44870000_44f00000 (1920, 1080) at +0xa0, and leaves the prefab and both
        // validation flags at their zero values.
        [Test]
        public void ConstructorSeedsTheOriginalDefaults()
        {
            UISystemConfiguration configuration = Create();
            try
            {
                Assert.That(configuration.AutoGeneratedCodeFolderPath, Is.EqualTo("Plugins/AutoGenerated"));
                Assert.That(configuration.AutoGeneratedUINamespace, Is.EqualTo("Hardlight"));
                Assert.That(configuration.AutoGeneratedUtilsNamespace, Is.EqualTo("Hardlight"));
                Assert.That(configuration.AutoGeneratedUIEnumComparerClassName, Is.EqualTo("HardlightEnumComparers"));
                Assert.That(configuration.TagNamesClassName, Is.EqualTo("TagName"));
                Assert.That(configuration.LayerNamesClassName, Is.EqualTo("LayerName"));
                Assert.That(configuration.UiSortingLayerNamesClassName, Is.EqualTo("SortingLayerName"));
                Assert.That(configuration.SceneNamesClassName, Is.EqualTo("SceneName"));
                Assert.That(configuration.PageTypeIdentifierEnumSuffix, Is.EqualTo("PageIdentifier"));
                Assert.That(configuration.SubPageTypeIdentifierEnumSuffix, Is.EqualTo("Identifier"));
                Assert.That(configuration.ProjectsAssetsFolderPath, Is.EqualTo("Assets/"));
                Assert.That(configuration.RootSceneFolderPath, Is.EqualTo("Scenes/"));
                Assert.That(configuration.CoreGUISceneFolderPath, Is.EqualTo("Scenes/Gui Pages/"));
                Assert.That(configuration.CoreGUISceneFolderWithAssetPath, Is.EqualTo("Assets/Scenes/Gui Pages/"));
                Assert.That(configuration.EnforcedTags, Is.EqualTo(new[] { "DevOnly", "GUIRoot", "GUICamera" }));
                Assert.That(configuration.EnforcedLayers, Is.EqualTo(new[] { "BackgroundUI", "MenuUI", "DialogUI", "ForegroundUI" }));
                Assert.That(configuration.EnforcedSortingLayers, Is.EqualTo(new[] {
                    "FX Background effects", "FX final effects", "Background", "Background PFX",
                    "Menu Background", "Menu Background PFX", "Menu Midground", "Menu Midground PFX",
                    "Menu Foreground", "Menu Foreground PFX", "Overlay Menu",
                    "Dialog Background", "Dialog Background PFX", "Dialog Midground", "Dialog Midground PFX",
                    "Dialog Foreground", "Dialog Foreground PFX", "Overlay Dialog",
                    "Foreground", "Foreground PFX", "Overlay Foreground", "Above All" }));
                Assert.That(configuration.DefaultReferenceResolutionForCanvasScaler, Is.EqualTo(new Vector2(1920f, 1080f)));
                Assert.That(configuration.SkipSceneValidationEventSystem, Is.False);
                Assert.That(configuration.SkipSceneValidationGUIRootTag, Is.False);
                Assert.That(configuration.UiCameraPrefab == null, Is.True);

                UISystemConfiguration second = Create();
                try
                {
                    Assert.That(second.EnforcedTags, Is.Not.SameAs(configuration.EnforcedTags), "each instance allocates its arrays");
                }
                finally { Object.DestroyImmediate(second); }
            }
            finally { Object.DestroyImmediate(configuration); }
        }

        // ---- getters 0x060000c7..0x060000db -------------------------------------

        // Each plain getter loads its own field (+0x18..+0xa9). Distinct values per field
        // catch a getter wired to a neighbour.
        [Test]
        public void EachGetterReadsItsOwnField()
        {
            UISystemConfiguration configuration = Create();
            var prefab = new GameObject("UI camera prefab fixture") { hideFlags = HideFlags.HideAndDontSave };
            try
            {
                string[] tags = { "t" }, layers = { "l" }, sortingLayers = { "s" };
                Set(configuration, "m_autoGeneratedCodeFolder", "a");
                Set(configuration, "m_autoGeneratedUINamespace", "b");
                Set(configuration, "m_autoGeneratedUtilsNamespace", "c");
                Set(configuration, "m_autoGeneratedUIEnumComparerClassName", "d");
                Set(configuration, "m_tagNamesClassName", "e");
                Set(configuration, "m_layerNamesClassName", "f");
                Set(configuration, "m_uiSortingLayerNamesClassName", "g");
                Set(configuration, "m_sceneNamesClassName", "h");
                Set(configuration, "m_pageTypeIdentifierEnumSuffix", "i");
                Set(configuration, "m_subPageTypeIdentifierEnumSuffix", "j");
                Set(configuration, "m_projectsAssetsFolderPath", "k");
                Set(configuration, "m_rootSceneFolderPath", "l");
                Set(configuration, "m_coreGUISceneFolderAdditonalPath", "m");
                Set(configuration, "m_uiCameraPrefab", prefab);
                Set(configuration, "m_enforcedTags", tags);
                Set(configuration, "m_enforcedLayers", layers);
                Set(configuration, "m_enforcedSortingLayers", sortingLayers);
                Set(configuration, "m_defaultReferenceResolutionForCanvasScaler", new Vector2(3f, 4f));
                Set(configuration, "m_skipSceneValidationEventSystem", true);

                Assert.That(new[] {
                    configuration.AutoGeneratedCodeFolderPath, configuration.AutoGeneratedUINamespace,
                    configuration.AutoGeneratedUtilsNamespace, configuration.AutoGeneratedUIEnumComparerClassName,
                    configuration.TagNamesClassName, configuration.LayerNamesClassName,
                    configuration.UiSortingLayerNamesClassName, configuration.SceneNamesClassName,
                    configuration.PageTypeIdentifierEnumSuffix, configuration.SubPageTypeIdentifierEnumSuffix,
                    configuration.ProjectsAssetsFolderPath, configuration.RootSceneFolderPath },
                    Is.EqualTo(new[] { "a", "b", "c", "d", "e", "f", "g", "h", "i", "j", "k", "l" }));
                Assert.That(configuration.UiCameraPrefab, Is.SameAs(prefab));
                Assert.That(configuration.EnforcedTags, Is.SameAs(tags));
                Assert.That(configuration.EnforcedLayers, Is.SameAs(layers));
                Assert.That(configuration.EnforcedSortingLayers, Is.SameAs(sortingLayers));
                Assert.That(configuration.DefaultReferenceResolutionForCanvasScaler, Is.EqualTo(new Vector2(3f, 4f)));
                Assert.That(configuration.SkipSceneValidationEventSystem, Is.True);
                Assert.That(configuration.SkipSceneValidationGUIRootTag, Is.False, "+0xa9 is a separate flag");
                Set(configuration, "m_skipSceneValidationEventSystem", false);
                Set(configuration, "m_skipSceneValidationGUIRootTag", true);
                Assert.That(configuration.SkipSceneValidationEventSystem, Is.False);
                Assert.That(configuration.SkipSceneValidationGUIRootTag, Is.True);
            }
            finally
            {
                Object.DestroyImmediate(prefab);
                Object.DestroyImmediate(configuration);
            }
        }

        // get_CoreGUISceneFolderPath (0x1b3f280) tail-calls String.Concat(root, additional)
        // and get_CoreGUISceneFolderWithAssetPath (0x1b3f2a0) Concat(assets, root, additional),
        // with no separator; Concat treats a null part as empty.
        [Test]
        public void SceneFolderPathsConcatenateTheirPartsWithoutSeparators()
        {
            UISystemConfiguration configuration = Create();
            try
            {
                Set(configuration, "m_projectsAssetsFolderPath", "Root");
                Set(configuration, "m_rootSceneFolderPath", "Scenes");
                Set(configuration, "m_coreGUISceneFolderAdditonalPath", "Pages");
                Assert.That(configuration.CoreGUISceneFolderPath, Is.EqualTo("ScenesPages"));
                Assert.That(configuration.CoreGUISceneFolderWithAssetPath, Is.EqualTo("RootScenesPages"));

                Set(configuration, "m_rootSceneFolderPath", null);
                Assert.That(configuration.CoreGUISceneFolderPath, Is.EqualTo("Pages"));
                Assert.That(configuration.CoreGUISceneFolderWithAssetPath, Is.EqualTo("RootPages"));
            }
            finally { Object.DestroyImmediate(configuration); }
        }

        // ---- NamedUnityEvent ----------------------------------------------------

        // dump.cs TypeDefIndex 12040: [Serializable] with two public fields in this order;
        // the constructor (0x1b6b520) only calls Object..ctor, so both start null.
        [Test]
        public void NamedUnityEventKeepsTwoPublicFieldsThatStartNull()
        {
            Type named = typeof(NamedUnityEvent);
            Assert.That(named.IsDefined(typeof(SerializableAttribute), false), Is.True);
            Assert.That(named.IsSealed, Is.False);
            Assert.That(named.BaseType, Is.EqualTo(typeof(object)));
            Assert.That(Il2CppOptions(named), Is.EqualTo(new[] { (int)Option.NullChecks, (int)Option.ArrayBoundsChecks }));
            FieldInfo[] fields = named.GetFields(InstanceFields);
            Assert.That(fields.Select(f => f.Name + ":" + f.FieldType.FullName), Is.EqualTo(new[] {
                "m_eventName:System.String", "m_event:UnityEngine.Events.UnityEvent" }));
            Assert.That(fields.All(f => f.IsPublic), Is.True);

            var instance = new NamedUnityEvent();
            Assert.That(instance.m_eventName, Is.Null);
            Assert.That(instance.m_event, Is.Null);
        }
    }
}
