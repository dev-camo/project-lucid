        Assert.AreEqual(1048577, (int)owner.Attributes);
        Assert.AreEqual(typeof(MonoBehaviour), owner.BaseType);
        Assert.AreEqual("UnityEngine.CoreModule", owner.BaseType.Assembly.GetName().Name);
        Assert.IsFalse(owner.IsGenericType);
        Assert.AreEqual("HLInput.Runtime", typeof(InputType).Assembly.GetName().Name);
        Assert.AreEqual("HLInput.Runtime", typeof(GlyphMappingDebugDisplay).Assembly.GetName().Name);
        Assert.AreEqual("HLAutoGenerated", typeof(GameInput).Assembly.GetName().Name);
        Assert.AreEqual("HLRTLTextMeshPro.Runtime", typeof(RTLTextMeshPro).Assembly.GetName().Name);
        Assert.AreEqual("HLUnityCore.Runtime", typeof(SystemRef<>).Assembly.GetName().Name);
        Assert.AreEqual("mscorlib", typeof(List<>).Assembly.GetName().Name);
        Assert.AreEqual("mscorlib", typeof(Comparison<>).Assembly.GetName().Name);
        IList<CustomAttributeData> options = owner.GetCustomAttributesData();
        Assert.AreEqual(2, options.Count);
        Option[] expectedOptions = { Option.NullChecks, Option.ArrayBoundsChecks };
        for (int i = 0; i < options.Count; i++)
        {
