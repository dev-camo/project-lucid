    [Test]
    public void DiscoveredGlyphComparatorCacheKeepsWholeRoleWithoutStaticValueReads()
    {
        Type owner = typeof(HLInputDebugMenu);
        Type cache = owner.GetNestedTypes(Declared).Single(t =>
            t.GetFields(Declared).Count(f => f.FieldType == t && f.IsStatic) == 1 &&
            t.GetFields(Declared).Count(f => f.FieldType == typeof(Comparison<GameInput>) && f.IsStatic) == 1);
        Assert.AreEqual(owner, cache.DeclaringType);
        Assert.AreEqual(owner.Assembly, cache.Assembly);
        Assert.AreEqual(owner.Namespace, cache.Namespace);
        Assert.AreEqual(1057027, (int)cache.Attributes);
        Assert.AreEqual(typeof(object), cache.BaseType);
        Assert.IsFalse(cache.IsGenericType);
        IList<CustomAttributeData> attributes = cache.GetCustomAttributesData();
        CustomAttributeData[] special = attributes.Where(a => a.AttributeType == typeof(SerializableAttribute)).ToArray();
        Assert.IsTrue(((int)cache.Attributes & 0x2000) != 0);
        Assert.AreEqual(1, special.Length);
        EmptyAttribute(special[0], typeof(SerializableAttribute), "mscorlib");
        CustomAttributeData[] raw = attributes.Where(a => a.AttributeType != typeof(SerializableAttribute)).ToArray();
        Assert.AreEqual(1, raw.Length);
        EmptyAttribute(raw[0], typeof(CompilerGeneratedAttribute), "mscorlib");
        // Serializable is a type-flag reflection pseudoattribute. Its separate raw
        // CAD/profile token is not equated to original raw ordered annotations.
        FieldInfo[] fields = cache.GetFields(Declared);
        Assert.AreEqual(2, fields.Length);
        FieldInfo singleton = fields.Single(f => f.FieldType == cache);
        Field(singleton, "<>9", cache, 54);
        FieldInfo comparator = fields.Single(f => f.FieldType == typeof(Comparison<GameInput>));
        Assert.IsTrue(comparator.Name.StartsWith("<>9__", StringComparison.Ordinal));
        Field(comparator, comparator.Name, typeof(Comparison<GameInput>), 22);
        foreach (FieldInfo field in fields) Assert.AreEqual(0, field.GetCustomAttributesData().Count);
        MethodInfo callback = cache.GetMethods(Declared).Single();
        Assert.IsTrue(callback.Name.StartsWith("<ToggleGlyphs>b__", StringComparison.Ordinal));
        Method(callback, 131, typeof(int), new[] { typeof(GameInput), typeof(GameInput) }, new[] { "x", "y" });
        Constructor(cache);
        ConstructorInfo initializer = cache.TypeInitializer;
        Assert.IsNotNull(initializer);
        Assert.AreEqual(6289, (int)initializer.Attributes);
        Assert.AreEqual(0, (int)initializer.GetMethodImplementationFlags());
        Parameters(initializer, Type.EmptyTypes, new string[0]);
        Assert.AreEqual(0, initializer.GetCustomAttributesData().Count);
        Assert.AreEqual(0, cache.GetInterfaces().Length);
        Assert.AreEqual(0, cache.GetProperties(Declared).Length);
        Assert.AreEqual(0, cache.GetEvents(Declared).Length);
        Assert.AreEqual(0, cache.GetNestedTypes(Declared).Length);
        // The original callback/cache ordinal17 remains in the preservation packet.
        // Current role discovery uses containing owner, literal field types and
        // callback contract. No delegate, static value or initializer is executed.
    }

    // Original <>c 0x020005f8 holds <>9__17_0 (0x04001524) and <ToggleGlyphs>b__17_0
    // (0x06002016, x86-64 0x560300), which boxes both GameInput values, calls
    // Enum.ToString on each and returns String.CompareOrdinal(x, y). UIBack sorts
    // before Up by name although its value is larger, so a numeric comparer, swapped
    // operands or a renumbered lambda ordinal fails here.
    [Test]
    public void GlyphComparatorKeepsOriginalCompilerNamesAndOrdinalEnumNameOrder()
    {
        Type cache = typeof(HLInputDebugMenu).GetNestedType("<>c", BindingFlags.NonPublic);
        Assert.IsNotNull(cache);
        Assert.IsNotNull(cache.GetField("<>9__17_0", Declared));
        MethodInfo callback = cache.GetMethod("<ToggleGlyphs>b__17_0", Declared);
        Assert.IsNotNull(callback);
        object instance = Activator.CreateInstance(cache);
        Func<GameInput, GameInput, int> compare = (x, y) => (int)callback.Invoke(instance, new object[] { x, y });
        Assert.That((int)GameInput.UIBack, Is.GreaterThan((int)GameInput.Up));
        Assert.That(compare(GameInput.UIBack, GameInput.Up), Is.LessThan(0));
        Assert.That(compare(GameInput.Up, GameInput.UIBack), Is.GreaterThan(0));
        Assert.That(compare(GameInput.UIRight, GameInput.UIRightSecondary), Is.LessThan(0));
        Assert.That(compare(GameInput.None, GameInput.None), Is.Zero);
    }

    private static void Field(FieldInfo field, string name, Type type, int flags)
    {
        Assert.AreEqual(name, field.Name); Assert.AreEqual(type, field.FieldType);
        Assert.AreEqual(flags, (int)field.Attributes);
        Assert.AreEqual((flags & 64) != 0, field.IsLiteral);
        Assert.IsFalse(field.IsNotSerialized);
    }

    private static void Method(MethodInfo method, int flags, Type result, Type[] types, string[] names)
    {
        Assert.IsNotNull(method); Assert.AreEqual(flags, (int)method.Attributes);
        Assert.AreEqual(0, (int)method.GetMethodImplementationFlags());
        Assert.AreEqual(result, method.ReturnType); Assert.IsFalse(method.IsGenericMethod);
        Parameters(method, types, names);
        Assert.AreEqual(0, method.GetCustomAttributesData().Count);
        // Original methods have a nil return Param token. Mono's synthetic return
        // flags/default projection is a separate raw/current profile observation.
        Assert.AreEqual(0, method.ReturnParameter.GetCustomAttributesData().Count);
    }

    private static void Constructor(Type type)
    {
        ConstructorInfo constructor = type.GetConstructors(InstanceConstructors).Single();
        Assert.AreEqual(6278, (int)constructor.Attributes);
        Assert.AreEqual(0, (int)constructor.GetMethodImplementationFlags());
        Parameters(constructor, Type.EmptyTypes, new string[0]);
        Assert.AreEqual(0, constructor.GetCustomAttributesData().Count);
    }

    private static void Parameters(MethodBase method, Type[] types, string[] names)
    {
        ParameterInfo[] parameters = method.GetParameters();
        CollectionAssert.AreEqual(types, parameters.Select(p => p.ParameterType).ToArray());
        CollectionAssert.AreEqual(names, parameters.Select(p => p.Name).ToArray());
        foreach (ParameterInfo parameter in parameters)
        {
            Assert.AreEqual(0, (int)parameter.Attributes); Assert.IsFalse(parameter.HasDefaultValue);
            Assert.AreEqual(0, parameter.GetCustomAttributesData().Count);
        }
    }

    private static void EmptyAttribute(CustomAttributeData attribute, Type type, string assembly)
    {
        Assert.AreEqual(type, attribute.AttributeType);
        Assert.AreEqual(assembly, attribute.AttributeType.Assembly.GetName().Name);
        Assert.AreEqual(0, attribute.Constructor.GetParameters().Length);
        Assert.AreEqual(0, attribute.ConstructorArguments.Count);
        Assert.AreEqual(0, attribute.NamedArguments.Count);
    }
}
