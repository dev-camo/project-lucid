        [Test]
        public void OriginalDeclarationsKeepScopedAuthoredRecordsAndAnnotations()
        {
            Type owner = typeof(GameLevelsWithLinkedTests);
            Assert.That(owner.Assembly.GetName().Name, Is.EqualTo("Game.Runtime"));
            Assert.That(owner.BaseType, Is.EqualTo(typeof(GameLevels)));
            Assert.That(typeof(ISerializationCallbackReceiver).IsAssignableFrom(owner), Is.True);
            Assert.That(owner.IsSerializable, Is.False);
            Type linked = typeof(GameLevelsWithLinkedTests.LinkedLevelsWithTests);
            Type level = typeof(GameLevelsWithLinkedTests.LevelData);
            foreach (Type record in new[] { linked, level })
            {
                Assert.That(record.DeclaringType, Is.EqualTo(owner));
                Assert.That(record.IsNestedPublic, Is.True);
                Assert.That(record.IsSerializable, Is.True);
                Assert.That(record.BaseType, Is.EqualTo(typeof(object)));
                RequireOptions(record);
            }
            RequireOptions(owner);
            var rootAttributes = owner.GetCustomAttributesData();
            Assert.That(rootAttributes.Select(a => a.AttributeType), Is.EqualTo(new[]
                { typeof(CreateAssetMenuAttribute), typeof(Il2CppSetOptionAttribute), typeof(Il2CppSetOptionAttribute) }));
            Assert.That(rootAttributes[0].Constructor.GetParameters(), Is.Empty);
            Assert.That(rootAttributes[0].ConstructorArguments, Is.Empty);
            Assert.That(rootAttributes[0].NamedArguments.Select(a => a.MemberName), Is.EqualTo(new[] { "fileName", "menuName" }));
            Assert.That(rootAttributes[0].NamedArguments.Select(a => a.IsField), Is.EqualTo(new[] { false, false }));
            Assert.That(rootAttributes[0].NamedArguments.Select(a => a.TypedValue.ArgumentType), Is.EqualTo(new[] { typeof(string), typeof(string) }));
            Assert.That(rootAttributes[0].NamedArguments.Select(a => a.TypedValue.Value), Is.EqualTo(new[]
                { "GameLevelWithTestsConfig", "HardlightProject/DefinitionData/Groups/Game Levels with Tests Configuration" }));
            Assert.That(typeof(AutoTestType).Assembly.GetName().Name, Is.EqualTo("HLAutoGenerated"));
            Assert.That(Enum.GetUnderlyingType(typeof(AutoTestType)), Is.EqualTo(typeof(int)));
            Assert.That((int)AutoTestType.CycleLevels, Is.EqualTo(-807588611));
            Assert.That((int)AutoTestType.InputReachDestination, Is.EqualTo(1340754004));
            Assert.That((int)AutoTestType.LoadLevel, Is.EqualTo(214172682));

            RequireFields(owner, new[] { "m_levelsWithLinkedTests" }, new[] { typeof(List<GameLevelsWithLinkedTests.LinkedLevelsWithTests>) }, false);
            RequireFields(linked, new[] { "Name", "TestType", "LevelData", "ExcludedLevels" }, new[] { typeof(string), typeof(AutoTestType), typeof(List<GameLevelsWithLinkedTests.LevelData>), typeof(List<GameplayLevelDefinition>) }, true);
            RequireFields(level, new[] { "Name", "TimeoutInSeconds", "Scene" }, new[] { typeof(string), typeof(int), typeof(GameplayLevelDefinition) }, true);
            FieldInfo rootList = owner.GetField("m_levelsWithLinkedTests", BindingFlags.Instance | BindingFlags.NonPublic | BindingFlags.DeclaredOnly);
            Assert.That(rootList.GetCustomAttributesData().Select(a => a.AttributeType), Is.EqualTo(new[] { typeof(SerializeField) }));
            foreach (Type record in new[] { linked, level })
                Assert.That(record.GetField("Name").GetCustomAttributesData().Select(a => a.AttributeType), Is.EqualTo(new[] { typeof(HideInInspector) }));

            MethodInfo apply = owner.GetMethod("ApplyToBuildSettings", BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly);
            Assert.That(apply.ReturnType, Is.EqualTo(typeof(void)));
            Assert.That(apply.GetParameters(), Is.Empty);
            var menu = apply.GetCustomAttributesData();
            Assert.That(menu.Count, Is.EqualTo(1));
            Assert.That(menu[0].AttributeType, Is.EqualTo(typeof(ContextMenu)));
            Assert.That(menu[0].Constructor.GetParameters().Select(p => p.ParameterType), Is.EqualTo(new[] { typeof(string) }));
            Assert.That(menu[0].ConstructorArguments.Count, Is.EqualTo(1));
            Assert.That(menu[0].ConstructorArguments[0].ArgumentType, Is.EqualTo(typeof(string)));
            Assert.That(menu[0].ConstructorArguments[0].Value, Is.EqualTo("Apply test scenes to build"));
            Assert.That(menu[0].NamedArguments, Is.Empty);
            // Serializable is checked through its original TypeDef flag. This
            // oracle does not equate projected CLR type CAD with physical CAD.
        }

        [Test]
        public void OwnedConstructorsAndCallbacksKeepOriginalNamesAndReferences()
        {
            WithOwned(1, owned =>
            {
                var config = owned[0];
                var authored = config.GameScenesWithTests;
                Assert.That(authored, Is.Not.Null.And.Empty);
                Assert.That(config.GameScenesWithTests, Is.SameAs(authored));
                var zero = new GameLevelsWithLinkedTests.LinkedLevelsWithTests();
                var named = new GameLevelsWithLinkedTests.LinkedLevelsWithTests { TestType = AutoTestType.LoadLevel };
                var entry = new GameLevelsWithLinkedTests.LevelData { Name = "retain-null-scene-name" };
                Assert.That(zero.Name, Is.Null);
                Assert.That((int)zero.TestType, Is.Zero);
                Assert.That(zero.LevelData, Is.Not.Null.And.Empty);
                Assert.That(zero.ExcludedLevels, Is.Not.Null.And.Empty);
                Assert.That(zero.LevelData, Is.Not.SameAs(named.LevelData));
                Assert.That(zero.ExcludedLevels, Is.Not.SameAs(named.ExcludedLevels));
                Assert.That(entry.TimeoutInSeconds, Is.Zero);
                Assert.That(entry.Scene, Is.Null);
                zero.LevelData.Add(entry);
                authored.Add(zero);
                authored.Add(named);
                config.OnBeforeSerialize();
                Assert.That(zero.Name, Is.EqualTo("0"));
                Assert.That(named.Name, Is.EqualTo("LoadLevel"));
                Assert.That(entry.Name, Is.EqualTo("retain-null-scene-name"));
                config.OnAfterDeserialize();
                Assert.That(config.GameScenesWithTests, Is.SameAs(authored));
                Assert.That(authored[0], Is.SameAs(zero));
                Assert.That(authored[0].LevelData[0], Is.SameAs(entry));
            });
        }

        [Test]
        public void NonCycleSearchSkipsUnmatchedDataAndContinuesAfterEmptyMatches()
        {
            WithOwned(1, owned =>
            {
                var config = owned[0];
                var entries = config.GameScenesWithTests;
                var unmatched = new GameLevelsWithLinkedTests.LinkedLevelsWithTests
                    { TestType = AutoTestType.InputReachDestination, LevelData = null };
                var emptyMatch = new GameLevelsWithLinkedTests.LinkedLevelsWithTests
                    { TestType = AutoTestType.LoadLevel };
                entries.Add(unmatched);
                entries.Add(emptyMatch);
                Assert.That(config.GetLevel("unused-owned-search", AutoTestType.LoadLevel), Is.Null);
                var laterMatch = new GameLevelsWithLinkedTests.LinkedLevelsWithTests
                    { TestType = AutoTestType.LoadLevel, LevelData = null };
                entries.Add(laterMatch);
                Assert.Throws<NullReferenceException>(() => config.GetLevel("unused-owned-search", AutoTestType.LoadLevel));
                entries.Clear();
                entries.Add(null);
                Assert.Throws<NullReferenceException>(() => config.GetLevel("unused-owned-search", AutoTestType.LoadLevel));
                entries.Clear();
                emptyMatch.LevelData.Add(null);
                entries.Add(emptyMatch);
                Assert.Throws<NullReferenceException>(() => config.GetLevel("unused-owned-search", AutoTestType.LoadLevel));
                // Fault oracles concern the rebuilt managed source. All cases
                // stop before SceneName; original AOT fault parity is unclaimed.
            });
        }

        [Test]
        public void OwnedJsonRoundTripKeepsNestedDataAndNullScene()
        {
            WithOwned(2, owned =>
            {
                var group = new GameLevelsWithLinkedTests.LinkedLevelsWithTests
                    { TestType = AutoTestType.InputReachDestination, Name = "before-callback" };
                group.LevelData.Add(new GameLevelsWithLinkedTests.LevelData
                    { Name = "authored-null-scene", TimeoutInSeconds = -7 });
                owned[0].GameScenesWithTests.Add(group);
                string json = JsonUtility.ToJson(owned[0]);
                JsonUtility.FromJsonOverwrite(json, owned[1]);
                Assert.That(owned[0].GameScenesWithTests[0].Name, Is.EqualTo("InputReachDestination"));
                var recovered = owned[1].GameScenesWithTests;
                Assert.That(recovered.Count, Is.EqualTo(1));
                Assert.That(recovered[0].TestType, Is.EqualTo(AutoTestType.InputReachDestination));
                Assert.That(recovered[0].Name, Is.EqualTo("InputReachDestination"));
                Assert.That(recovered[0].ExcludedLevels, Is.Not.Null.And.Empty);
                Assert.That(recovered[0].LevelData.Count, Is.EqualTo(1));
                Assert.That(recovered[0].LevelData[0].Name, Is.EqualTo("authored-null-scene"));
                Assert.That(recovered[0].LevelData[0].TimeoutInSeconds, Is.EqualTo(-7));
                Assert.That(recovered[0].LevelData[0].Scene, Is.Null);
                Assert.That(recovered, Is.Not.SameAs(owned[0].GameScenesWithTests));
                Assert.That(recovered[0], Is.Not.SameAs(group));
                Assert.That(recovered[0].LevelData, Is.Not.SameAs(group.LevelData));
            });
        }

        private static void RequireFields(Type owner, string[] names, Type[] types, bool isPublic)
        {
            var fields = owner.GetFields(BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly).OrderBy(f => f.MetadataToken).ToArray();
            Assert.That(fields.Select(f => f.Name), Is.EqualTo(names));
            Assert.That(fields.Select(f => f.FieldType), Is.EqualTo(types));
            foreach (var field in fields)
            {
                Assert.That(field.IsPublic, Is.EqualTo(isPublic));
                Assert.That(field.IsPrivate, Is.EqualTo(!isPublic));
                Assert.That(field.IsStatic || field.IsInitOnly || field.IsLiteral, Is.False);
            }
        }

        private static void RequireOptions(Type owner)
        {
            var options = owner.GetCustomAttributesData().Where(a => a.AttributeType == typeof(Il2CppSetOptionAttribute)).ToArray();
            Assert.That(options.Length, Is.EqualTo(2));
            Option[] order = { Option.NullChecks, Option.ArrayBoundsChecks };
            for (int i = 0; i < order.Length; i++)
            {
                Assert.That(options[i].Constructor.GetParameters().Select(p => p.ParameterType), Is.EqualTo(new[] { typeof(Option), typeof(object) }));
                Assert.That(options[i].ConstructorArguments.Count, Is.EqualTo(2));
                Assert.That(options[i].ConstructorArguments[0].ArgumentType, Is.EqualTo(typeof(Option)));
                Assert.That(options[i].ConstructorArguments[0].Value, Is.EqualTo((int)order[i]));
                Assert.That(options[i].ConstructorArguments[1].ArgumentType, Is.EqualTo(typeof(bool)));
                Assert.That(options[i].ConstructorArguments[1].Value, Is.EqualTo(false));
                Assert.That(options[i].NamedArguments, Is.Empty);
            }
        }

        private static void WithOwned(int count, Action<GameLevelsWithLinkedTests[]> action)
        {
            var owned = new GameLevelsWithLinkedTests[count];
            ExceptionDispatchInfo primary = null;
            var cleanupFailures = new List<Exception>();
            try
            {
                for (int i = 0; i < count; i++) owned[i] = ScriptableObject.CreateInstance<GameLevelsWithLinkedTests>();
                action(owned);
            }
            catch (Exception failure) { primary = ExceptionDispatchInfo.Capture(failure); }
            finally
            {
                foreach (var asset in owned)
                {
                    if (ReferenceEquals(asset, null)) continue;
                    try { UnityEngine.Object.DestroyImmediate(asset); }
                    catch (Exception failure) { cleanupFailures.Add(failure); }
                }
            }
            if (primary != null)
            {
                try
                {
                    foreach (var failure in cleanupFailures) TestContext.Error.WriteLine("Secondary owned cleanup failure: " + failure);
                }
                finally { primary.Throw(); }
            }
            if (cleanupFailures.Count != 0) throw new AggregateException("Owned cleanup failed", cleanupFailures);
        }
