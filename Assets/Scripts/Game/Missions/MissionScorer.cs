            out float score, out bool usesComboMultiplier)
        {
            foreach (MissionScorerStreak streak in streaks)
                if (streak.TryUpdateFromObjective(streakObjective, out score, out usesComboMultiplier)) return true;
            score = 0f;
            usesComboMultiplier = false;
            return false;
        }
