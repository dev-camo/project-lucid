        private void UpdateStreaks(float deltaTime)
        {
            foreach (MissionScorerStreak streak in m_streaksManual) streak.Update(deltaTime);
            foreach (MissionScorerStreak streak in m_streaksAuto) streak.Update(deltaTime);
        }

        // Original 0x06002782: Write both out cells zero/false before the actual MissionScorerStreakObjective type test. Try manual then auto lists with short-circuit priority. A matched objective returns whether the score is strictly positive, retaining the matched out bool even when false.
        public bool UpdateStreak(MissionScorerObjective objective, out float streakScore, out bool usesComboMultiplier)
        {
            streakScore = 0f;
            usesComboMultiplier = false;
            if (!(objective is MissionScorerStreakObjective streakObjective)) return false;
