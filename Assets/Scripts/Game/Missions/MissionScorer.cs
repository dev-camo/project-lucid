        // Original 0x06002774: Update manual then auto streaks before the ComboSuspended early return. Otherwise update timeout or multiplier drain, then score and streak display clocks. Keep stage division and provider float/fault semantics held.
        protected override void InternalUpdate(float deltaTime)
        {
            UpdateStreaks(deltaTime);
            if (ComboSuspended) return;
            if (ComboTimeout > 0f)
            {
                ComboTimeout -= deltaTime;
                ComboTimeoutNormalised = ComboTimeout / m_comboStage.ComboTimeLimit;
                ComboActive = true;
                if (ComboTimeout <= 0f) EndCombo();
            }
            else if (m_comboStage.DrainPerSecond > 0f && ComboMultiplier > 1f)
            {
                ComboActive = true;
                ComboMultiplier -= m_comboStage.DrainPerSecond * deltaTime;
                if (ComboMultiplier <= 1f) EndCombo();
            }
            if (m_scoreTimeout > 0f)
                m_scoreTimeout = Mathf.Max(m_scoreTimeout - deltaTime, 0f);
            if (m_streakTimeout > 0f)
            {
                m_streakTimeout -= deltaTime;
                if (m_streakTimeout <= 0f)
                {
                    m_streakTimeout = 0f;
                    PointsTotalThisStreak = 0;
                }
            }
        }

        // Original 0x06002775: Exact zero input returns before stage or event access. Store the stage multiplier, round the left-associated multiplied score, add unchecked totals, choose streak or combo display writes, then invoke m_onAddPoints.
        public void AddPoints(float pointsToAdd, bool isStreak)
        {
            if (pointsToAdd == 0f) return;
            ComboStageMultiplier = m_comboStage.ComboMultiplier;
            int points = Mathf.RoundToInt(ComboMultiplier * pointsToAdd * ComboStageMultiplier);
            PointsTotal = unchecked(PointsTotal + points);
            if (isStreak)
            {
                PointsTotalThisStreak = points;
                m_streakTimeout = m_displayTimer;
            }
            else
            {
                PointsTotalThisCombo = unchecked(PointsTotalThisCombo + points);
                PointsAdded = points;
                PointsAddedRaw = Mathf.RoundToInt(pointsToAdd);
                PointsAddedFromCombo = true;
                m_scoreTimeout = m_displayTimer;
            }
            m_onAddPoints.Invoke();
        }

        // Original 0x06002776: Exact zero input returns before event access. Round the input once without combo multiplication, add unchecked totals, select streak or combo display writes, then invoke m_onAddPointsFlat.
        public void AddPointsFlat(float pointsToAdd, bool isStreak)
        {
            if (pointsToAdd == 0f) return;
            int points = Mathf.RoundToInt(pointsToAdd);
            PointsTotal = unchecked(PointsTotal + points);
            if (isStreak)
            {
                PointsTotalThisStreak = points;
                m_streakTimeout = m_displayTimer;
            }
            else
            {
                PointsTotalThisCombo = unchecked(PointsTotalThisCombo + points);
                PointsAdded = points;
                PointsAddedRaw = points;
                PointsAddedFromCombo = false;
                m_scoreTimeout = m_displayTimer;
            }
            m_onAddPointsFlat.Invoke();
        }

        // Original 0x06002777: Round the input, subtract unchecked totals, clamp each total to zero when negative points are disabled, store PointsLost, then invoke m_onLosePoints. Zero input still reaches the callback.
        public void LosePoints(float pointsToLose)
        {
            int points = Mathf.RoundToInt(pointsToLose);
            PointsTotal = unchecked(PointsTotal - points);
            PointsTotalThisCombo = unchecked(PointsTotalThisCombo - points);
            if (!m_allowNegativePoints)
            {
                PointsTotal = Mathf.Max(PointsTotal, 0);
                PointsTotalThisCombo = Mathf.Max(PointsTotalThisCombo, 0);
            }
            PointsLost = points;
            m_onLosePoints.Invoke();
        }

        // Original 0x06002778: Apply the stage maximum to the increased multiplier, copy the stage multiplier, and increment ComboCount unchecked even for zero increase.
        public void IncreaseCombo(float increase)
        {
            ComboMultiplier = Mathf.Min(ComboMultiplier + increase, m_comboStage.MaxCombo);
            ComboStageMultiplier = m_comboStage.ComboMultiplier;
            ComboCount = unchecked(ComboCount + 1);
        }

        // Original 0x06002779: Set stage index zero, take the genuine first list item, clear ComboAtMax and PointsTotalThisCombo, then perform all six EndCombo writes. Empty/null list faults remain provider and source-form holds.
        public void ResetComboStage()
        {
            m_comboStageIndex = 0;
            m_comboStage = m_comboStages[0];
            ComboAtMax = false;
            PointsTotalThisCombo = 0;
            EndCombo();
        }

        // Original 0x0600277a: Negative or out-of-count stage index returns. Otherwise store the stage, reduce timeout to its limit, divide for normalisation, apply IncreaseCombo(0), set the final-stage flag, and clear PointsTotalThisCombo. The native zero addition is optimized away.
        public void SetComboStage(int stageIndex)
        {
            if (stageIndex < 0 || stageIndex >= m_comboStages.Count) return;
            m_comboStageIndex = stageIndex;
            m_comboStage = m_comboStages[stageIndex];
            ComboTimeout = Mathf.Min(ComboTimeout, m_comboStage.ComboTimeLimit);
            ComboTimeoutNormalised = ComboTimeout / m_comboStage.ComboTimeLimit;
            IncreaseCombo(0f);
            ComboAtMax = m_comboStageIndex == m_comboStages.Count - 1;
            PointsTotalThisCombo = 0;
        }

        // Original 0x0600277b: Increment the current stage index unchecked and tailcall SetComboStage; do not clamp or wrap the list index.
