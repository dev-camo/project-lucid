        // Original 0x0600277e: Store multipliers one and one, timeout and normalisation zero, count zero, and active false. Preserve all other state including ComboSuspended and PointsTotalThisCombo.
        public void EndCombo()
        {
            ComboMultiplier = 1f;
            ComboStageMultiplier = 1f;
            ComboTimeout = 0f;
            ComboTimeoutNormalised = 0f;
            ComboCount = 0;
