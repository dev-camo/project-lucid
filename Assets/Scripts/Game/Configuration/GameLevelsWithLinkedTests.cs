        public GameplayLevelDefinition GetLevel(string sceneName, AutoTestType testType)
        {
            if (testType == AutoTestType.CycleLevels) return base.GetLevel(sceneName);
            foreach (var test in m_levelsWithLinkedTests)
            {
                if (test.TestType != testType) continue;
                foreach (var level in test.LevelData)
                {
                    var scene = level.Scene;
                    if (scene.SceneName != sceneName) continue;
                    return scene;
                }
            }
            return null;
        }

        public List<GameplayLevelDefinition> GetLevels(AutoTestType testType)
        {
            var levels = new List<GameplayLevelDefinition>(base.GetLevels());
            // Closure 0x0200041a: constructor 0x06001824, predicate 0x06001825.
            var linked = m_levelsWithLinkedTests.Find(test => test.TestType == testType);
            for (int i = levels.Count - 1; i >= 0; i--)
                if (linked.ExcludedLevels.Contains(levels[i])) levels.RemoveAt(i);
            return levels;
        }

        public void OnBeforeSerialize()
        {
            foreach (var test in m_levelsWithLinkedTests)
            {
                test.Name = test.TestType.ToString();
                foreach (var level in test.LevelData)
                    if (level.Scene != null) level.Name = level.Scene.SceneName;
            }
        }

