using System;
using System.Collections.Generic;
using Unity.IL2CPP.CompilerServices;
using UnityEngine;

namespace HardlightProject
{
    [CreateAssetMenu(fileName = "GameLevelWithTestsConfig", menuName = "HardlightProject/DefinitionData/Groups/Game Levels with Tests Configuration")]
    [Il2CppSetOption(Option.NullChecks, false)]
    [Il2CppSetOption(Option.ArrayBoundsChecks, false)]
    public class GameLevelsWithLinkedTests : GameLevels, ISerializationCallbackReceiver
    {
        [Serializable]
        [Il2CppSetOption(Option.NullChecks, false)]
        [Il2CppSetOption(Option.ArrayBoundsChecks, false)]
        public class LinkedLevelsWithTests
        {
            [HideInInspector] public string Name;
            public AutoTestType TestType;
            public List<LevelData> LevelData = new List<LevelData>();
            public List<GameplayLevelDefinition> ExcludedLevels = new List<GameplayLevelDefinition>();

            public LinkedLevelsWithTests() { }
        }

        [Serializable]
        [Il2CppSetOption(Option.NullChecks, false)]
        [Il2CppSetOption(Option.ArrayBoundsChecks, false)]
        public class LevelData
        {
            [HideInInspector] public string Name;
            public int TimeoutInSeconds;
            public GameplayLevelDefinition Scene;

            public LevelData() { }
        }

        [SerializeField]
        private List<LinkedLevelsWithTests> m_levelsWithLinkedTests = new List<LinkedLevelsWithTests>();

        public List<LinkedLevelsWithTests> GameScenesWithTests => m_levelsWithLinkedTests;

        public override void Validate() { }

        [ContextMenu("Apply test scenes to build")]
        public override void ApplyToBuildSettings() { }

        public GameplayLevelDefinition GetLevel(string sceneName, AutoTestType testType)
        {
            if (testType == AutoTestType.CycleLevels) return base.GetLevel(sceneName);
            foreach (var test in m_levelsWithLinkedTests)
            {
                if (test.TestType != testType) continue;
                foreach (var level in test.LevelData)
                {
                    var scene = level.Scene;
                    if (scene.SceneName != sceneName) continue;
                    return scene;
                }
            }
            return null;
        }

        public List<GameplayLevelDefinition> GetLevels(AutoTestType testType)
        {
            var levels = new List<GameplayLevelDefinition>(base.GetLevels());
            var linked = m_levelsWithLinkedTests.Find(test => test.TestType == testType);
            for (int i = levels.Count - 1; i >= 0; i--)
                if (linked.ExcludedLevels.Contains(levels[i])) levels.RemoveAt(i);
            return levels;
        }

        public void OnBeforeSerialize()
        {
            foreach (var test in m_levelsWithLinkedTests)
            {
                test.Name = test.TestType.ToString();
                foreach (var level in test.LevelData)
                    if (level.Scene != null) level.Name = level.Scene.SceneName;
            }
        }

        public void OnAfterDeserialize() { }

        public GameLevelsWithLinkedTests() { }
    }
}
