    // Original marker interfaces genuinely have no
    // members. Restore only the original concrete MethodDef flag bits; no method
    // bodies, marker contracts, fields, scopes, tokens or symbols are rewritten.
    public sealed class CodecMethodFlagsPostProcessor : ILPostProcessor
    {
        public override ILPostProcessor GetInstance() => new CodecMethodFlagsPostProcessor();
        public override bool WillProcess(ICompiledAssembly assembly) => assembly.Name == "HLAutoGenerated";

        public override ILPostProcessResult Process(ICompiledAssembly assembly)
        {
            if (!WillProcess(assembly)) return null;
            try
            {
                byte[] result = CodecFlags.Restore(assembly.InMemoryAssembly.PeData, assembly.References);
                return new ILPostProcessResult(new InMemoryAssembly(result, assembly.InMemoryAssembly.PdbData));
            }
            catch (Exception error) when (error is InvalidDataException || error is IOException || error is InvalidOperationException || error is AssemblyResolutionException || error is BadImageFormatException || error is OverflowException || error is ArgumentException || error is IndexOutOfRangeException)
            {
                // Never return partially patched bytes. Unity's Error diagnostic
                // must stop compilation until the exact source graph is present.
                return new ILPostProcessResult(assembly.InMemoryAssembly, new List<DiagnosticMessage> {
                    new DiagnosticMessage { DiagnosticType = DiagnosticType.Error, MessageData = "Codec metadata restoration refused: " + error.Message }
                });
            }
        }
    }

